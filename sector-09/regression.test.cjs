const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const get=n=>fs.readFileSync(path.join(__dirname,n),'utf8');
const html=get('index.html'),scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
for(const s of scripts)new Function(s);
for(const f of ['online-engine.js','online-round.js','online-lobby.js','menu-launcher.js','polish.js'])new Function(get(f));
const maps=JSON.parse(html.match(/const MAPS=(\[.*?\]);let map=/s)[1]);
const mod={exports:{}};new Function('module',get('online-engine.js'))(mod);
const E=mod.exports.Sector09Engine;
const roster=Array.from({length:6},(_,i)=>({uid:'test'+i,name:'Unit '+i,bot:i>=2}));
for(const m of maps){
 const g=E.create(m,{density:6,difficulty:'normal'},roster,0);
 assert.ok(g.units.every(u=>E.walkable(m,u.x,u.y)));
 assert.ok(E.snapshot(g).units.every(u=>!('agent' in u)&&!('uid' in u)&&!('cool' in u)));
 assert.equal(E.role(g,'test0').agent,true);
 E.step(g,.05,{test1:{action:{n:1,kind:'task',target:0}}});
 assert.equal(g.tasks[0].done,false);
 for(let i=0;i<3600&&g.phase!=='end';i++)E.step(g,.05,{});
 assert.ok(g.units.every(u=>E.walkable(m,u.x,u.y)));
 assert.ok(g.tasks.some(t=>t.done),'bot progress');
 const v=E.create(m,{density:4},roster.map(r=>({...r,bot:false})),0);
 E.step(v,.05,{test1:{action:{n:1,kind:'meeting'}}});
 assert.equal(v.phase,'vote');
 E.step(v,.05,Object.fromEntries(roster.map((r,i)=>[r.uid,{action:{n:2,kind:'vote',meeting:v.meetingId,target:i===0?-1:0}}])));
 assert.equal(v.winner,'crew');
 console.log(m.id+': passed');
}
const rules=JSON.parse(fs.readFileSync(path.join(__dirname,'../firebase/database.rules.json'),'utf8')).rules;
assert.equal(rules.sector09Rounds.$code['.read'],undefined);
assert.match(rules.sector09Rounds.$code.roles.$uid['.read'],/auth.uid === \$uid/);
assert.match(rules.sector09Rounds.$code.inputs.$uid['.write'],/auth.uid === \$uid/);
assert.match(rules.sector09Invites.$to.$from['.write'],/blocked/);
console.log('Syntax, maps, bot progress, votes, role isolation rule structure: OK');
